def criar_grafo():
    G = nx.DiGraph()
    G.add_nodes_from(nodes)

    for i in range(len(nodes)):
        for j in range(len(nodes)):
            weight = adj_matrix[i][j]

            if weight > 0:
                G.add_edge(
                    nodes[i],
                    nodes[j],
                    weight=weight
                )

    return G

